<?php
/**
 * Regenerates ARCHITECTURE.md — a live map of the codebase.
 * Run: php tools/map.php
 */
$root = dirname(__DIR__);
require $root.'/vendor/autoload.php';
$app = require $root.'/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();

$ls = function (string $dir, string $ext = 'php') use ($root) {
    $path = $root.'/'.$dir;
    if (!is_dir($path)) return [];
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS));
    $out = [];
    foreach ($it as $f) {
        if ($f->getExtension() === $ext || ($ext === 'jsx' && in_array($f->getExtension(), ['jsx','js']))) {
            $out[] = str_replace(DIRECTORY_SEPARATOR, '/', substr($f->getPathname(), strlen($root) + 1));
        }
    }
    sort($out);
    return $out;
};

$rows = [];
foreach (app('router')->getRoutes() as $r) {
    $action = $r->getActionName();
    if (str_contains($action, 'vendor')) continue;
    $methods = implode('|', array_diff($r->methods(), ['HEAD']));
    $handler = $action === 'Closure' ? '(closure)' : ltrim(strrchr($action, chr(92)) ?: $action, chr(92));
    $rows[] = sprintf('| `%s` | `/%s` | %s |', $methods, ltrim($r->uri(), '/'), $handler);
}

$section = function (string $title, array $files) {
    if (!$files) return '';
    return "### $title\n\n".implode("\n", array_map(fn ($f) => "- `$f`", $files))."\n\n";
};

$md  = "# Architecture map\n\n";
$md .= "_Generated by `php tools/map.php` — do not edit by hand._\n\n";
$md .= "Generated: ".date('Y-m-d H:i')."\n\n---\n\n";
$md .= "## Routes (".count($rows).")\n\n| Method | URI | Handler |\n|---|---|---|\n".implode("\n", $rows)."\n\n---\n\n";
$md .= "## Backend\n\n";
$md .= $section('Controllers', $ls('app/Http/Controllers'));
$md .= $section('Services (business logic)', $ls('app/Services'));
$md .= $section('Models', $ls('app/Models'));
$md .= $section('Migrations', $ls('database/migrations'));
$md .= "---\n\n## Frontend\n\n";
$md .= $section('Pages & views', $ls('resources/js/Pages', 'jsx'));
$md .= "---\n\n## Where to look\n\n";
$md .= "| Want to change... | Go to |\n|---|---|\n";
$md .= "| Match scoring / thresholds | `app/Services/MatchService.php` |\n";
$md .= "| What the dashboards receive | `app/Http/Controllers/DashboardController.php` |\n";
$md .= "| Applicant screens | `resources/js/Pages/SkillBridge/views/UserProfile.jsx` |\n";
$md .= "| Employer screens | `resources/js/Pages/SkillBridge/views/EmployerDashboard.jsx` |\n";
$md .= "| Public landing page | `resources/js/Pages/SkillBridge/views/GeneralDashboard.jsx` |\n";
$md .= "| Colors & fonts | `resources/js/Pages/SkillBridge/styles/ui.js` |\n";
$md .= "| Nav / profile menu | `resources/js/Pages/SkillBridge/SkillBridgePage.jsx` |\n";
$md .= "| Login / signup | `resources/js/Pages/JobSeeker/` + `app/Http/Controllers/Auth/` |\n";
$md .= "| Database shape | `database/migrations/` |\n";

file_put_contents($root.'/ARCHITECTURE.md', $md);
echo "ARCHITECTURE.md written (".count($rows)." routes)\n";
